"""Configura no projeto os perfis presentes na composição dos squads selecionados."""
import argparse
import json
import os
from pathlib import Path
import re
import stat
import sys
import tempfile

try:
    import tomllib
except ModuleNotFoundError:
    sys.exit("O utilitário opcional requer Python 3.11 ou mais recente. Use a cópia local dos modelos descrita na skill.")


ASSETS = Path(__file__).resolve().parents[1] / "assets"
SQUADS = ASSETS / "manual" / "squads"
MEMBRO = re.compile(r"^- \[([A-Za-z]+) · [^\]]+\]\(\.\./agentes/([a-z0-9-]+)\.md\)$")


def carregar_modelos(escolhas, disponiveis):
    if not disponiveis:
        raise ValueError("Nenhuma composição de squad disponível no pacote.")
    perfis = {}
    for squad in (disponiveis if "todos" in escolhas else dict.fromkeys(escolhas)):
        ficha = (SQUADS / (squad + ".md")).read_text(encoding="utf-8")
        _, separador, resto = ficha.partition("\n## Composição do catálogo\n")
        composicao = resto.split("\n## ", 1)[0].strip().splitlines()
        if not separador or not composicao:
            raise ValueError(f"Composição de squad ausente: {squad}")
        for linha in composicao:
            membro = MEMBRO.fullmatch(linha)
            if not membro:
                raise ValueError(f"Composição de squad inválida: {squad}")
            nome, perfil = membro.groups()
            if perfil in perfis:
                continue
            ficha_perfil = (ASSETS / "manual" / "agentes" / (perfil + ".md")).read_text(encoding="utf-8")
            origem = re.search(r"^\*\*Função de origem\*\* `([a-z]+(?:_[a-z]+)*)`[ \t]*$", ficha_perfil, re.M)
            if not origem or not ficha_perfil.startswith(f"# {nome} · "):
                raise ValueError(f"Ficha de especialista inconsistente: {perfil}")
            rotulo = f"{nome} {origem[1].replace('_', ' ')} zaip agent"
            arquivo = nome.lower() + ".toml"
            conteudo = (ASSETS / "subagentes" / arquivo).read_bytes()
            modelo = tomllib.loads(conteudo.decode("utf-8"))
            if modelo.get("name") != rotulo.lower().replace(" ", "_") or modelo.get("nickname_candidates") != [rotulo]:
                raise ValueError(f"O modelo {arquivo} difere da identidade do catálogo.")
            perfis[perfil] = (arquivo, conteudo, modelo)
    return perfis.values()


def tipo_local(caminho):
    try:
        info = caminho.lstat()
    except FileNotFoundError:
        return None
    if stat.S_ISLNK(info.st_mode) or getattr(info, "st_file_attributes", 0) & stat.FILE_ATTRIBUTE_REPARSE_POINT:
        raise ValueError(f"Caminho indireto preservado: {caminho}")
    return info.st_mode


def conferir_diretorio(caminho, criar=False):
    for atual in (*reversed(caminho.parents), caminho):
        modo = tipo_local(atual)
        if modo is None and criar:
            atual.mkdir(exist_ok=True)
            modo = tipo_local(atual)
        if modo is None or not stat.S_ISDIR(modo):
            raise ValueError(f"Diretório indisponível: {atual}")


def preparar_destino(projeto):
    conferir_diretorio(projeto)
    destino = projeto / ".codex" / "agents"
    globais = [Path.home() / ".codex"]
    if os.environ.get("CODEX_HOME"):
        globais.append(Path(os.environ["CODEX_HOME"]))
    if projeto.resolve() == Path.home().resolve() or any(
        destino.resolve().is_relative_to(p.resolve()) for p in globais
    ):
        raise ValueError("Escolha a pasta da empresa, fora do perfil pessoal do Codex.")
    orientacoes = projeto / "AGENTS.md"
    modo = tipo_local(orientacoes)
    if modo is not None:
        if not stat.S_ISREG(modo):
            raise ValueError("AGENTS.md precisa ser um arquivo local regular.")
        with orientacoes.open("rb") as entrada:
            cabecalho = entrada.read(4096)
        codificacao = "utf-16" if cabecalho.startswith((b"\xff\xfe", b"\xfe\xff")) else "utf-8-sig"
        linhas = cabecalho.decode(codificacao, errors="replace").casefold().splitlines()[:12]
        for linha in linhas:
            if "zaip" in linha and re.search(r"\b(gerado pelo instalador|gerenciado pelo|generated by|managed by)\b", linha):
                raise ValueError("O cabeçalho de AGENTS.md indica uma instalação gerenciada.")
    catalogo = projeto
    for parte in (".agents", "config", "agents", "catalog.yaml"):
        catalogo = catalogo / parte
        if tipo_local(catalogo) is None:
            break
    else:
        raise ValueError("O catálogo de agentes da instalação completa foi preservado.")
    conferir_diretorio(destino, criar=True)
    return destino


def ja_configurado(pasta, arquivo, esperado):
    encontrados = []
    for caminho in pasta.iterdir():
        if caminho.suffix.lower() != ".toml":
            continue
        mesmo_arquivo = caminho.name.casefold() == arquivo.casefold()
        modo = tipo_local(caminho)
        if modo is None:
            continue
        if not stat.S_ISREG(modo):
            if mesmo_arquivo:
                raise ValueError(f"O destino {caminho.name} não é um arquivo regular.")
            continue
        try:
            atual = tomllib.loads(caminho.read_text(encoding="utf-8-sig"))
        except (UnicodeDecodeError, tomllib.TOMLDecodeError):
            if mesmo_arquivo:
                raise ValueError(f"O arquivo existente {caminho.name} não pôde ser interpretado.")
            continue
        nome = atual.get("name")
        if mesmo_arquivo or (isinstance(nome, str) and nome.casefold() == esperado["name"].casefold()):
            if atual != esperado:
                raise ValueError(f"O perfil local em {caminho.name} usa esta identidade ou destino com outra configuração.")
            encontrados.append(caminho.name)
    if len(encontrados) > 1:
        raise ValueError(f"A identidade aparece em mais de um perfil: {', '.join(encontrados)}")
    return bool(encontrados)


def instalar(pasta, arquivo, conteudo, modelo):
    conferir_diretorio(pasta)
    if ja_configurado(pasta, arquivo, modelo):
        return "reutilizados"
    saida = tempfile.NamedTemporaryFile(dir=pasta, suffix=".tmp", delete=False)
    temporario = Path(saida.name)
    try:
        with saida:
            saida.write(conteudo)
        conferir_diretorio(pasta)
        if ja_configurado(pasta, arquivo, modelo):
            return "reutilizados"
        destino = pasta / arquivo
        try:
            # Disponibilize o TOML inteiro de uma só vez e preserve um destino criado em paralelo.
            if os.name == "nt":
                os.rename(temporario, destino)
            else:
                os.link(temporario, destino)
        except FileExistsError:
            if ja_configurado(pasta, arquivo, modelo):
                return "reutilizados"
            raise
        if not ja_configurado(pasta, arquivo, modelo):
            raise ValueError(f"Não foi possível confirmar {arquivo} após a cópia.")
        return "criados"
    finally:
        temporario.unlink(missing_ok=True)


def main():
    disponiveis = sorted(p.stem for p in SQUADS.glob("squad-*.md"))
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--projeto", required=True, type=Path)
    parser.add_argument("squads", nargs="+", choices=[*disponiveis, "todos"])
    args = parser.parse_args()
    resultado = {"criados": [], "reutilizados": [], "pendentes": []}
    try:
        modelos = carregar_modelos(args.squads, disponiveis)
        try:
            pasta = preparar_destino(args.projeto.absolute())
        except (OSError, ValueError) as erro:
            for _, _, modelo in modelos:
                resultado["pendentes"].append({"nome": modelo["name"], "motivo": str(erro)})
        else:
            for arquivo, conteudo, modelo in modelos:
                try:
                    estado = instalar(pasta, arquivo, conteudo, modelo)
                    resultado[estado].append(modelo["name"])
                except (OSError, ValueError) as erro:
                    resultado["pendentes"].append({"nome": modelo["name"], "motivo": str(erro)})
    except (OSError, ValueError) as erro:
        resultado["erro"] = str(erro)
    print(json.dumps(resultado, ensure_ascii=True))
    return int(bool(resultado["pendentes"] or resultado.get("erro")))


if __name__ == "__main__":
    sys.exit(main())
